"""Generate experiments/local_llm/SUMMARY.md from every arm's saved results.

Reads only what the runner wrote to disk (arm.json, {paper}/run.json,
scores.json), so it can be re-run at any time without touching a model.

Usage:
    .venv/bin/python -m pipeline.experiments.local_llm_report
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

import yaml

from pipeline.evaluation.fields import HEADLINE_GROUPS
from pipeline.experiments.run_local_llm_benchmark import ARMS_YAML, BENCH_ROOT, _papers_smallest_first
from pipeline.experiments.select_sample import load_sample

SUMMARY_MD = BENCH_ROOT / "SUMMARY.md"
GROUP_COLUMNS = [
    "identity", "thermal", "conductivity", "transport", "molecular_weight",
    "classification", "processing", "fits", "curator_computed",
]


def _md_table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    lines += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def _pct(x: float | None) -> str:
    return "–" if x is None else f"{100 * x:.0f}%"


def _load_arm(name: str) -> dict | None:
    arm_dir = BENCH_ROOT / name
    if not (arm_dir / "arm.json").exists():
        return None
    runs = {}
    for run_json in sorted(arm_dir.glob("*/run.json")):
        r = json.loads(run_json.read_text())
        runs[r["paper_id"]] = r
    scores = json.loads((arm_dir / "scores.json").read_text()) if (arm_dir / "scores.json").exists() else None
    return {"arm": json.loads((arm_dir / "arm.json").read_text()), "runs": runs, "scores": scores}


def _null_share(raw_path: Path) -> tuple[int, int] | None:
    """(characters spent on explicit-null fields, total characters) of one reply."""
    if not raw_path.exists():
        return None
    text = json.loads(raw_path.read_text()).get("raw_text") or ""
    try:
        records = json.loads(text).get("formulations", [])
    except (json.JSONDecodeError, AttributeError):
        return None
    # `"key": null,` plus the line break and indentation a pretty-printer puts before it.
    null_chars = sum(len(json.dumps(k)) + len(": null,") for r in records for k, v in r.items() if v is None)
    if "\n" in text:
        null_chars += sum(1 for r in records for v in r.values() if v is None) * 7
    return null_chars, len(text)


def _impossible_conductivities(arm_dir: Path) -> tuple[int, int, int]:
    """(zeros, negatives, all filled) among predicted conductivity values.

    A conductivity can't be zero or negative, so these are never readings:
    zeros are placeholders for "no data" (a 4B model told not to write null
    wrote 374 of them on one paper), negatives are log10(sigma) values written
    into a sigma field.
    """
    zeros = negatives = filled = 0
    for ext in arm_dir.glob("*/extraction.json"):
        for rec in json.loads(ext.read_text()).get("formulations", []):
            for k, v in rec.items():
                if k.startswith("Conductivity at ") and isinstance(v, (int, float)):
                    filled += 1
                    zeros += v == 0
                    negatives += v < 0
    return zeros, negatives, filled


def build_report() -> str:
    arms_def = yaml.safe_load(ARMS_YAML.read_text())["arms"]
    sample = load_sample()
    loaded = {name: _load_arm(name) for name in arms_def}
    done = {k: v for k, v in loaded.items() if v}
    if not done:
        return "# Local-LLM benchmark\n\nNo arm has been run yet.\n"
    any_arm = next(iter(done.values()))
    gold_rows = any_arm["scores"]["formulations"]["gold_rows"] if any_arm["scores"] else "?"

    out = [
        "# Local-LLM benchmark — Round 1",
        "",
        "_Generated by `pipeline/experiments/local_llm_report.py` from `experiments/local_llm/*/`; "
        "do not edit by hand._",
        "",
        f"Sample: the pinned {len(sample['papers'])}-paper benchmark set (seed {sample['seed']}), "
        f"**{gold_rows} golden formulations**. Machine: MacBook Air M4, 24 GB, fanless. "
        f"Runtime: `{any_arm['arm']['llama_cpp']}`. Every arm: non-thinking, temperature 0.2, "
        "seed 0, JSON-schema-constrained output, prompt cache off (cold-read timings).",
        "",
        "## How to read this",
        "",
        "- **Memory** is llama.cpp's own breakdown at startup (GPU + host buffers: weights, KV cache, compute), "
        "plus the vision encoder's file size for arms with figures. **Fits** compares it with ⅔ of the tier's RAM, "
        "what macOS lets the GPU use on an 8–32 GB machine. (The OS's own peak-memory figure is recorded in "
        "`arm.json` but undercounts: it leaves out the memory-mapped model file.)",
        "- **Formulations found** = golden formulations paired with a predicted one, out of all golden "
        "formulations. Pairing is on anion + salt concentration (see `pipeline/evaluation/rowmatch.py`); "
        "*rank* pairings, made by concentration order when the paper and the golden set state concentration "
        "in different units, are counted in brackets. **Precision** = predicted formulations that paired, "
        "out of all predicted.",
        "- **Accuracy** = correct cells out of the golden-filled cells *in paired rows*: when the model finds "
        "a formulation, how right is it. **Recall** = correct cells out of the golden-filled cells in *all* "
        "golden rows: a missed formulation costs every one of its cells.",
        f"- **Headline** pools the groups whose values a paper normally prints: {', '.join(HEADLINE_GROUPS)}. "
        "`curator_computed` (SMILES, functional groups per monomer, the curators' own fits) is shown but "
        "never in the headline.",
        "- **Conductivity** is right if within 0.1 decades of the golden value (about ±26%); *loose* allows "
        "0.5 decades (about ×3), the realistic bar for a value read off a log-scale plot.",
        "- A blank golden cell is never counted against a model. Cells the model filled where the golden set "
        "is blank are counted in `scores.json` as *extra*, not scored.",
        "",
        "## Results by arm",
        "",
    ]

    rows = []
    for name, d in done.items():
        a, s = d["arm"], d["scores"]
        mem = a.get("memory") or {}
        runs = list(d["runs"].values())
        ok = [r for r in runs if r["status"] == "ok"]
        walls = [r["wall_seconds"] for r in ok if r.get("wall_seconds")]
        decode = [r["predicted_per_second"] for r in ok if r.get("predicted_per_second")]
        f = s["formulations"] if s else {}
        g = s["groups"] if s else {}
        head = g.get("HEADLINE", {})
        cond = g.get("conductivity", {})
        rows.append([
            f"**{name}**",
            f"{a['arm']['tier']} GB",
            "yes" if a["arm"]["include_figures"] else "no",
            f"{mem.get('total_mib', '?')} / {mem.get('tier_budget_mib', '?')}",
            "✅" if mem.get("fits_tier") else ("❌" if mem else "?"),
            f"{len(ok)}/{len(sample['papers'])}",
            f"{f.get('matched', 0)}/{f.get('gold_rows', '?')} ({f.get('matched_rank', 0)} rank)" if f else "–",
            _pct(f.get("precision")),
            _pct(head.get("accuracy")),
            _pct(head.get("recall")),
            f"{_pct(cond.get('accuracy'))} / {_pct(cond.get('accuracy_loose'))}",
            f"{statistics.median(walls):.0f}" if walls else "–",
            f"{statistics.median(decode):.1f}" if decode else "–",
        ])
    out.append(_md_table(
        ["Arm", "Tier", "Figures", "Memory MiB (used / budget)", "Fits", "Papers OK", "Formulations found",
         "Precision", "Headline accuracy", "Headline recall", "Conductivity (tight / loose)",
         "Median s/paper", "Median decode tok/s"],
        rows,
    ))

    out += ["", "## Efficiency", "",
            "Measured on the MacBook Air M4 (fanless: long runs slow down as it heats up). *Reading* is prompt "
            "processing (prefill), *writing* is generation (decode); on a laptop writing is the slow part. "
            "*Empty-field share* is the fraction of output characters spent writing fields as `null` -- "
            "time that produces no data.", ""]
    rows = []
    for name, d in done.items():
        mem = d["arm"].get("memory") or {}
        ok = [r for r in d["runs"].values() if r["status"] == "ok"]
        runs_all = list(d["runs"].values())
        total_s = sum(r["wall_seconds"] or 0 for r in runs_all)
        prefill = [r["prompt_per_second"] for r in ok if r.get("prompt_per_second")]
        decode = [r["predicted_per_second"] for r in ok if r.get("predicted_per_second")]
        out_tok = sum(r["completion_tokens"] or 0 for r in ok)
        n_form = sum(r["n_formulations"] or 0 for r in ok)
        shares = [x for x in (_null_share(BENCH_ROOT / name / pid / "raw_llm_response.json") for pid in d["runs"]) if x]
        null_share = sum(a for a, _ in shares) / sum(b for _, b in shares) if shares and sum(b for _, b in shares) else None
        rows.append([
            name,
            f"{mem.get('total_mib', '?')} / {mem.get('tier_budget_mib', '?')}",
            f"{total_s / 60:.0f} min",
            f"{statistics.median([r['wall_seconds'] for r in ok]):.0f}" if ok else "–",
            f"{statistics.median(prefill):.0f}" if prefill else "–",
            f"{statistics.median(decode):.1f}" if decode else "–",
            out_tok,
            f"{out_tok / n_form:.0f}" if n_form else "–",
            _pct(null_share),
        ])
    out.append(_md_table(
        ["Arm", "Memory MiB (used / budget)", "Total time, all papers", "Median s/paper",
         "Reading tok/s", "Writing tok/s", "Output tokens", "Output tokens per formulation", "Empty-field share"],
        rows,
    ))

    out += ["", "## Accuracy by field group (paired rows)", "",
            "Each cell: accuracy, with the number of golden-filled cells it is out of.", ""]
    rows = []
    for name, d in done.items():
        g = (d["scores"] or {}).get("groups", {})
        rows.append([name] + [
            f"{_pct(g[c]['accuracy'])} ({g[c]['gold_cells_matched']})" if g.get(c, {}).get("gold_cells_matched") else "–"
            for c in GROUP_COLUMNS
        ])
    out.append(_md_table(["Arm"] + GROUP_COLUMNS, rows))

    out += ["", "## Per paper", "",
            "Formulations: paired / golden (predicted). Papers are listed smallest first, the order they ran in.", ""]
    gold_rows_by_paper = {
        p["paper_id"]: p["gold_rows"] for d in done.values() if d["scores"] for p in d["scores"]["per_paper"]
    }
    headers = ["Paper", "Golden rows"] + list(done)
    rows = []
    for pid in _papers_smallest_first():
        gold = gold_rows_by_paper.get(pid, "?")
        row = [pid, gold]
        for d in done.values():
            r = d["runs"].get(pid)
            sp = next((p for p in (d["scores"] or {}).get("per_paper", []) if p["paper_id"] == pid), None)
            if not r:
                row.append("not run")
            elif r["status"] != "ok":
                row.append(f"❌ {r['wall_seconds']}s")
            else:
                paired = f"{sp['matched']}/{gold} ({sp['pred_rows']})" if sp else f"not scored yet ({r['n_formulations']})"
                row.append(f"{paired} · {r['wall_seconds']:.0f}s · {r['completion_tokens']} tok")
        rows.append(row)
    out.append(_md_table(headers, rows))

    out += ["", "## Impossible conductivity values", "",
            "Conductivity is always positive, so a predicted value of zero or below is not a reading: zeros are "
            "placeholders for missing data, negatives are log10(σ) written into a σ field. Both score as wrong.", ""]
    rows = []
    for name in done:
        zeros, negatives, filled = _impossible_conductivities(BENCH_ROOT / name)
        rows.append([name, filled, zeros, negatives, _pct((zeros + negatives) / filled) if filled else "–"])
    out.append(_md_table(["Arm", "Conductivity values filled", "Zeros", "Negative (log σ)", "Impossible share"], rows))

    problems = []
    for name, d in done.items():
        for r in d["runs"].values():
            if r["status"] != "ok":
                problems.append(f"- `{name}` / `{r['paper_id']}`: {r['error']}")
            elif r.get("cache_n"):
                problems.append(f"- `{name}` / `{r['paper_id']}`: {r['cache_n']} prompt tokens came from cache "
                                "(timing is not a cold read)")
    out += ["", "## Failures and anomalies", ""] + (problems or ["None."])
    return "\n".join(out) + "\n"


def main() -> None:
    SUMMARY_MD.write_text(build_report(), encoding="utf-8")
    print(f"Wrote {SUMMARY_MD}")


if __name__ == "__main__":
    main()
